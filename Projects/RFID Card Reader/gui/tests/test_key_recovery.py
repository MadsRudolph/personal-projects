def test_nested_recover_known_key():
    """Test nested recovery with synthetic nonce pairs."""
    from key_recovery import find_prng_distance, _bswap32

    # find_prng_distance expects wire-order (big-endian) inputs.
    # Generate values: pick internal-order start, advance PRNG, byte-swap to wire.
    nt_internal = 0x01020304
    nt_target_internal = prng_successor(nt_internal, 200)
    nt_wire = _bswap32(nt_internal)
    nt_target_wire = _bswap32(nt_target_internal)

    dist = find_prng_distance(nt_wire, nt_target_wire, max_dist=1000)
    assert dist == 200


def test_find_prng_distance():
    from key_recovery import find_prng_distance, _bswap32
    # Internal-order values, then byte-swap to wire order for the function
    nt_internal = 0xAABBCCDD
    target_internal = prng_successor(nt_internal, 42)
    assert find_prng_distance(_bswap32(nt_internal), _bswap32(target_internal), 100) == 42


