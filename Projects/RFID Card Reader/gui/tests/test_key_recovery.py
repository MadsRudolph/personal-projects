def test_calibrate_nested_distance():
    """Calibration finds correct PRNG distance using known key."""
    from key_recovery import calibrate_nested_distance, _bswap32

    uid_wire = 0xE413B3DA
    known_key = bytes.fromhex("FFFFFFFFFFFF")
    nt_known_wire = 0x01020304
    dist = 160

    # Generate encrypted nonce in internal order (matching Python crypto1)
    uid_le = _bswap32(uid_wire)
    nt_known_le = _bswap32(nt_known_wire)
    nt_pred = prng_successor(nt_known_le, dist)
    c = Crypto1(known_key)
    ks32 = c.crypto1_word(uid_le ^ nt_pred, 0)
    nt_target_enc_le = nt_pred ^ ks32
    # Convert encrypted nonce back to wire order for the function
    nt_target_enc_wire = _bswap32(nt_target_enc_le)

    result = calibrate_nested_distance(uid_wire, nt_known_wire, nt_target_enc_wire, known_key)
    assert result == dist


